import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
execFileSync('forge', ['build', '--ast'], { cwd: root, stdio: 'pipe' })
const compiled = JSON.parse(readFileSync(new URL('../guard-artifacts/RailgunExecutionGuard.sol/RailgunExecutionGuard.json', import.meta.url)))
const contract = compiled.ast.nodes.find((node) => node.nodeType === 'ContractDefinition' && node.name === 'RailgunExecutionGuard')
const immutables = Object.fromEntries(contract.nodes
  .filter((node) => node.nodeType === 'VariableDeclaration' && node.mutability === 'immutable')
  .map((node) => [node.name, compiled.deployedBytecode.immutableReferences[node.id]]))
assert.deepEqual(Object.keys(immutables), ['operator', 'delegate', 'delegateCodeHash', 'authorizationCodeHash'])
assert.equal(compiled.metadata.compiler.version, '0.8.30+commit.73712a01')
assert(Object.values(immutables).every((refs) => refs.length && refs.every((ref) => ref.length === 32)))
const artifact = { compiler: compiled.metadata.compiler.version,
  sourceSHA256: createHash('sha256').update(readFileSync(new URL('../contracts/RailgunExecutionGuard.sol', import.meta.url))).digest('hex'),
  abi: compiled.abi, bytecode: compiled.bytecode.object, runtime: compiled.deployedBytecode.object, immutables }
const output = '// Generated by apps/broadcaster/scripts/guard-artifact.mjs; verify with pnpm test:guard.\n' +
  'export const GUARD_ARTIFACT = ' + JSON.stringify(artifact, null, 2) + ' as const\n'
const target = new URL('../../railgun/operator/execution-guard-artifact.ts', import.meta.url)
if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8'), output, 'Guard artifact differs from the pinned source/compiler output.')
else writeFileSync(target, output)
console.log('Guard source and reproducible artifact verified.')
