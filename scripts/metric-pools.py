#!/usr/bin/env python3
"""Regenerate (or check) the generated part of the pinned Metric pool table.

  python3 scripts/metric-pools.py           rewrite the table in place
  python3 scripts/metric-pools.py --check   exit 1 if the table has drifted

Rule: Metric v1 pools on Robinhood (4663) under the pinned factory and quoter
that are unpaused and traded at least 10,000 USD in the prior 7 days, at most
six per pair by that volume. Pools listed above the BEGIN marker are reviewed
by hand, never touched here, and count toward their pair's six.

The price-feed status is deliberately not part of the rule: stock feeds go
down outside market hours and flap within them, and the solver already skips
any pool whose live quote reverts.

The Metric API only proposes pools. Each one is then read onchain (factory
isPool, pool getImmutables) and dropped with an error if the chain disagrees.
"""
import json
import os
import re
import sys
import urllib.request

TABLE = "apps/backend/crates/shared/src/metric.rs"
BEGIN = "    // BEGIN GENERATED by scripts/metric-pools.py\n"
END = "    // END GENERATED\n"
API = "https://api.metric.xyz/public/v1/evm/4663/metadata?count=500&minTvlFiat=0&offset=%d"
RPC = os.environ.get("ROBINHOOD_RPC", "https://rpc.mainnet.chain.robinhood.com")
FACTORY = "0x2a53833cc95548cf52c7b159110e22D3a9018f32"
QUOTER = "0x3B9ea79f482094323d06064E637a7F4528560fcb"
USDG = "0x5fc5360D0400a0Fd4f2af552ADD042D716F1d168"
MIN_VOLUME_USD, PER_PAIR = 10_000, 6
ADDRESS = re.compile(r"0x[0-9a-fA-F]{40}")


def fetch(url, body=None):
    request = urllib.request.Request(
        url, data=body, headers={"content-type": "application/json", "user-agent": "metric-pools/1"}
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def eth_call(to, data):
    body = {"jsonrpc": "2.0", "id": 1, "method": "eth_call", "params": [{"to": to, "data": data}, "latest"]}
    return fetch(RPC, json.dumps(body).encode())["result"]


def word(address):
    return address[2:].lower().rjust(64, "0")


def onchain(pool, token0, token1):
    """True only if the factory registered the pool and its immutables name these tokens."""
    registered = eth_call(FACTORY, "0x5b16ebb7" + word(pool))  # isPool(address)
    immutables = eth_call(pool, "0xbcdb4dad")[2:]  # getImmutables()
    return int(registered, 16) == 1 and immutables[: 3 * 64] == word(FACTORY) + word(token0) + word(token1)


ROW = re.compile(
    r'\(\s*address!\("([0-9a-fA-F]{40})"\),\s*address!\("([0-9a-fA-F]{40})"\),'
    r'\s*(?:USDG|address!\("([0-9a-fA-F]{40})"\)),\s*\)'
)


def rows_of(text):
    return [(pool.lower(), t0.lower(), (t1 or USDG[2:]).lower()) for pool, t0, t1 in ROW.findall(text)]


def row(p):
    return tuple(p[k][2:].lower() for k in ("poolAddress", "token0", "token1"))


def main():
    source = open(TABLE).read()
    head, rest = source.split(BEGIN)
    generated, tail = rest.split(END)
    # Rows as lowercase (pool, token0, token1), read from the Rust source.
    reviewed = rows_of(head[head.index("pub const POOLS") :])
    current = set(rows_of(generated))
    # Every `(` entry in the generated block must parse as a full row.
    if len(rows_of(generated)) != generated.count("    (\n"):
        sys.exit("unparseable generated row in the table")
    if len(rows_of(generated)) != len(current):
        sys.exit("duplicate generated rows in the table")

    pools, offset = [], 0
    while offset is not None:
        page = fetch(API % offset)
        pools += page["data"]
        offset = page.get("nextOffset")

    def volume(pool):
        return ((pool.get("volumeByWindow") or {}).get("7d")) or 0

    eligible = [
        p
        for p in pools
        if p.get("contractVersion") == "v1"
        and p.get("poolFactoryAddress") == FACTORY
        and p.get("quoterAddress") == QUOTER
        and p.get("pauseLevel") == 0
        and volume(p) >= MIN_VOLUME_USD
        and all(ADDRESS.fullmatch(str(p.get(k))) for k in ("poolAddress", "token0", "token1"))
    ]
    eligible.sort(key=volume, reverse=True)
    taken = {}
    for _, token0, token1 in reviewed:  # reviewed pools hold a slot whatever their state
        taken[(token0, token1)] = taken.get((token0, token1), 0) + 1
    reviewed_pools = {pool for pool, _, _ in reviewed}
    chosen = []
    for p in eligible:
        pair = row(p)[1:]
        if row(p)[0] in reviewed_pools or taken.get(pair, 0) >= PER_PAIR:
            continue
        if not onchain(p["poolAddress"], p["token0"], p["token1"]):
            sys.exit("chain disagrees with the Metric API about pool %s" % p["poolAddress"])
        taken[pair] = taken.get(pair, 0) + 1
        chosen.append(p)

    wanted = {row(p) for p in chosen}
    if "--check" in sys.argv:
        for p in pools:
            if str(p.get("poolAddress", ""))[2:].lower() in reviewed_pools and p.get("pauseLevel") != 0:
                print("reviewed pool is paused (edit by hand): %s" % p["poolAddress"])
        for entry in sorted(wanted - current):
            print("missing from the table: 0x%s (tokens 0x%s, 0x%s)" % entry)
        for entry in sorted(current - wanted):
            print("no longer eligible: 0x%s (tokens 0x%s, 0x%s)" % entry)
        if wanted != current:
            sys.exit("pinned Metric pools drifted; run: python3 scripts/metric-pools.py")
        print("pinned Metric pools match the rule (%d generated)" % len(current))
        return

    rows = ""
    for p in chosen:
        # API text only ever lands in a comment, reduced to a safe alphabet.
        label = re.sub(r"[^A-Za-z0-9/._-]", "?", str(p.get("pair", "")))[:24]
        token1 = "USDG" if p["token1"] == USDG else 'address!("%s")' % p["token1"][2:]
        rows += '    // %s\n    (\n        address!("%s"),\n        address!("%s"),\n        %s,\n    ),\n' % (
            label,
            p["poolAddress"][2:],
            p["token0"][2:],
            token1,
        )
    open(TABLE, "w").write(head + BEGIN + rows + END + tail)
    print("wrote %d generated pools (+%d, -%d)" % (len(chosen), len(wanted - current), len(current - wanted)))


if __name__ == "__main__":
    main()
